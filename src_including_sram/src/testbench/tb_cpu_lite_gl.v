`timescale 1ns/1ps
// Gate-level TB: runs program_memory.hex on the post-ECO netlist until HALT, checks R0-R15.
module tb_cpu_lite_gl;
parameter real CPU_HALF = 3.333, MEM_HALF = 7.143;
parameter integer TIMEOUT = 2000000;
parameter integer WINDOW  = 2000;

reg clk_cpu, clk_mem, rst;
wire [31:0] prog_data;
wire [11:0] pc;

cpu_lite dut(.clk_cpu(clk_cpu), .clk_mem(clk_mem), .rst(rst),
             .program_memory_data(prog_data), .program_memory_addr(pc));
program_memory prog(.pc(pc), .program_memory_data(prog_data));

initial clk_cpu = 1'b0;
initial clk_mem = 1'b0;
always #CPU_HALF clk_cpu = ~clk_cpu;
always #MEM_HALF clk_mem = ~clk_mem;

`ifdef SDF
initial $sdf_annotate("cpu_lite_eco.sdf", dut, , "sdf.log", "MAXIMUM");
`endif

// Register probes into the netlist (generated by the perl script)
wire [511:0] gpr;
`include "gpr_probe.vh"

integer cycles, i, pass_count, fail_count, win, lo, hi, done;
reg [31:0] exp [0:15];
reg [31:0] got;

integer k;
initial begin
    for (k = 0; k < `numWords; k = k + 1) memory[k] = 1'b0;
    data_out = 1'b0;          // SRAM1RW512x32_1bit
end
initial begin
    $printtimescale;
    pass_count = 0; fail_count = 0;
    exp[0]=32'h00004100; exp[1]=32'h00000140; exp[2]=32'h00000000; exp[3]=32'h0000033F;
    exp[4]=32'h000000BF; exp[5]=32'h00001820; exp[6]=32'h00000D94; exp[7]=32'h00000D94;
    exp[8]=32'h000017E0; exp[9]=32'h00002920; exp[10]=32'h000017E0; exp[11]=32'h000002D0;
    exp[12]=32'h043FE482; exp[13]=32'h0000000D; exp[14]=32'h00003FFF; exp[15]=32'h000000BF;

    rst = 1'b1; #5 rst = 1'b0; #50 rst = 1'b1;

    cycles = 0; win = 0; lo = 4095; hi = 0; done = 0;
    while (!done && cycles < TIMEOUT) begin
        @(posedge clk_cpu); cycles = cycles + 1;
        if (^pc !== 1'bx) begin
            if (pc < lo) lo = pc;
            if (pc > hi) hi = pc;
        end
        win = win + 1;
        if (win == WINDOW) begin
            if (lo <= hi && (hi - lo) <= 3) done = 1;
            else begin win = 0; lo = 4095; hi = 0; end
        end
    end
    if (!done) $display("[FAIL] no HALT within %0d cycles (pc=%h)", TIMEOUT, pc);
    else       $display("HALT detected near pc=%0d after ~%0d cycles", lo, cycles - WINDOW);

    repeat (20) @(posedge clk_cpu); #1;
    for (i = 0; i < 16; i = i + 1) begin
        got = gpr[i*32 +: 32];
        if (got === exp[i]) begin pass_count = pass_count + 1; $display("[PASS] R%0d = 0x%h", i, got); end
        else begin fail_count = fail_count + 1; $display("[FAIL] R%0d = 0x%h, expected 0x%h", i, got, exp[i]); end
    end
    $display("TOTAL: %0d  PASS: %0d  FAIL: %0d", pass_count+fail_count, pass_count, fail_count);
    $finish;
end

// Early sanity print: reset should have been applied by now
initial begin
    #100 $display("t=%0t rst=%b pc=%h R14[0]=%b", $time, rst, pc, gpr[14*32]);
end
endmodule
